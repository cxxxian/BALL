using UnityEngine;

/// <summary>
/// 运行时生成 Matrix 代码雨用等宽小写字母图集（5×7 点阵，无外部贴图依赖）。
/// </summary>
public static class MatrixGlyphAtlas
{
    public const int GlyphsPerRow = 8;
    public const int GlyphCount = 36;
    public const int CellPixels = 16;

    // 每字符 7 行，每行 5 bit（1=笔画画素）— 顺序 a-z, 0-9
    private static readonly byte[][] Glyphs =
    {
        new byte[] { 0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 }, // a
        new byte[] { 0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E }, // b
        new byte[] { 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E }, // c
        new byte[] { 0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E }, // d
        new byte[] { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F }, // e
        new byte[] { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10 }, // f
        new byte[] { 0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F }, // g
        new byte[] { 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 }, // h
        new byte[] { 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E }, // i
        new byte[] { 0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C }, // j
        new byte[] { 0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11 }, // k
        new byte[] { 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F }, // l
        new byte[] { 0x11, 0x1B, 0x15, 0x11, 0x11, 0x11, 0x11 }, // m
        new byte[] { 0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11 }, // n
        new byte[] { 0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E }, // o
        new byte[] { 0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10 }, // p
        new byte[] { 0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D }, // q
        new byte[] { 0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11 }, // r
        new byte[] { 0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E }, // s
        new byte[] { 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04 }, // t
        new byte[] { 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E }, // u
        new byte[] { 0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04 }, // v
        new byte[] { 0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11 }, // w
        new byte[] { 0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11 }, // x
        new byte[] { 0x11, 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04 }, // y
        new byte[] { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F }, // z
        new byte[] { 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E }, // 0
        new byte[] { 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E }, // 1
        new byte[] { 0x0E, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1F }, // 2
        new byte[] { 0x1F, 0x01, 0x02, 0x06, 0x01, 0x01, 0x0E }, // 3
        new byte[] { 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02 }, // 4
        new byte[] { 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E }, // 5
        new byte[] { 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E }, // 6
        new byte[] { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08 }, // 7
        new byte[] { 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E }, // 8
        new byte[] { 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C }, // 9
    };

    public static Texture2D CreateAtlas()
    {
        int cols = GlyphsPerRow;
        int rows = (GlyphCount + cols - 1) / cols;
        int texW = cols * CellPixels;
        int texH = rows * CellPixels;

        var tex = new Texture2D(texW, texH, TextureFormat.RGBA32, false)
        {
            filterMode = FilterMode.Point,
            wrapMode = TextureWrapMode.Clamp,
            name = "MatrixGlyphAtlas"
        };

        var pixels = new Color32[texW * texH];
        for (int i = 0; i < pixels.Length; i++)
            pixels[i] = new Color32(0, 0, 0, 0);

        for (int i = 0; i < GlyphCount; i++)
        {
            int cx = i % cols;
            int cy = i / cols;
            BlitGlyph(pixels, texW, texH, cx * CellPixels, cy * CellPixels, Glyphs[i]);
        }

        tex.SetPixels32(pixels);
        tex.Apply(false, true);
        return tex;
    }

    public static void ApplyToMaterial(Material mat, Texture2D atlas)
    {
        if (mat == null || atlas == null) return;
        mat.SetTexture("_GlyphAtlas", atlas);
        mat.SetFloat("_GlyphsPerRow", GlyphsPerRow);
        mat.SetFloat("_GlyphRows", Mathf.CeilToInt(GlyphCount / (float)GlyphsPerRow));
        mat.SetFloat("_GlyphCount", GlyphCount);
    }

    private static void BlitGlyph(Color32[] pixels, int texW, int texH, int ox, int oy, byte[] rows)
    {
        const int glyphW = 5;
        const int glyphH = 7;
        int padX = (CellPixels - glyphW) / 2;
        int padY = (CellPixels - glyphH) / 2;

        for (int y = 0; y < glyphH; y++)
        {
            byte row = rows[y];
            for (int x = 0; x < glyphW; x++)
            {
                bool on = ((row >> (4 - x)) & 1) == 1;
                if (!on) continue;

                int px = ox + padX + x;
                int py = oy + padY + (glyphH - 1 - y);
                if (px < 0 || py < 0 || px >= texW || py >= texH) continue;
                pixels[py * texW + px] = new Color32(255, 255, 255, 255);
            }
        }
    }
}
